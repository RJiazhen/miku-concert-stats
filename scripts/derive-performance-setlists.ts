import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import Database from 'better-sqlite3'
import { applyCatalogSql, repoRoot } from './build-catalog.ts'
import { loadCatalog } from '../shared/catalog.ts'
import { reviewRotations } from '../shared/rotation.ts'
import {
  buildPerformanceSetlists,
  parsePerformanceSetlistCuration,
  validateCurationAgainstCatalog,
  type PerformanceSetlistBuild,
  type PerformanceSetlistCurationIndex,
} from '../shared/performance-setlists.ts'
import { chunkInserts } from './sql/emit.ts'
import type { SqlRow } from '../shared/types.ts'

const TARGET = path.join('data', 'increments', '0008-performance-setlists.sql')
const CURATION = path.join('data', 'performance-setlists.json')

/** Builds the catalog from the committed SQL so the derivation matches what the site shows. */
const readCatalog = (root: string) => {
  const db = new Database(':memory:')
  try {
    applyCatalogSql(db, root)
    return loadCatalog({
      /** Runs one read-only query against the in-memory catalog. */
      all: (sql: string) => db.prepare(sql).all() as SqlRow[],
    })
  } finally {
    db.close()
  }
}

/** Reads the hand-checked curation file, treating a missing file as empty. */
const readCuration = (root: string): unknown => {
  try {
    return JSON.parse(readFileSync(path.join(root, CURATION), 'utf8'))
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
      return { version: 1, performances: {}, lists: {} }
    }
    throw error
  }
}

/** Renders the derivation as one replaceable increment. */
export const renderPerformanceSetlists = (build: PerformanceSetlistBuild, retrievedAt: string): string => {
  const parts: string[] = [
    '-- Derived 演出-layer setlists, generated by scripts/derive-performance-setlists.ts.',
    '-- Source: data/increments/0001-vocadb-catalog.sql, 0004-album-setlists.sql,',
    '--         and data/performance-setlists.json (hand-checked sources and corrections).',
    `-- Generated: ${retrievedAt}`,
    '-- Replaces the derived tables. Re-run `pnpm derive:setlists` after any source change.',
    'DELETE FROM medley_songs;',
    'DELETE FROM medleys;',
    'DELETE FROM performance_show_setlist_items;',
    'DELETE FROM performance_show_setlists;',
    'DELETE FROM performance_setlist_sources;',
    'DELETE FROM performance_setlists;',
  ]
  const append = (sql: string): void => {
    if (sql) parts.push(sql)
  }
  append(
    chunkInserts(
      'performance_setlists',
      [
        'performance_id',
        'source_list_id',
        'source_kind',
        'change',
        'status',
        'resolution',
        'source_row_count',
        'day_night_dates',
        'no_show_dates',
        'single_show_dates',
        'conflict',
        'pending_review',
        'note',
      ],
      build.setlists.map((row) => [
        row.performance_id,
        row.source_list_id,
        row.source_kind,
        row.change,
        row.status,
        row.resolution,
        row.source_row_count,
        row.day_night_dates,
        row.no_show_dates,
        row.single_show_dates,
        row.conflict,
        row.pending_review,
        row.note,
      ]),
    ),
  )
  append(
    chunkInserts(
      'performance_setlist_sources',
      ['performance_id', 'url', 'title', 'accessed_at', 'confidence', 'note', 'conflict'],
      build.sources.map((row) => [
        row.performance_id,
        row.url,
        row.title,
        row.accessed_at,
        row.confidence,
        row.note,
        row.conflict,
      ]),
    ),
  )
  append(
    chunkInserts(
      'performance_show_setlists',
      ['performance_id', 'show_key', 'date', 'half', 'item_count', 'omitted_count', 'uncertain', 'reasons'],
      build.shows.map((row) => [
        row.performance_id,
        row.show_key,
        row.date,
        row.half,
        row.item_count,
        row.omitted_count,
        row.uncertain,
        row.reasons,
      ]),
    ),
  )
  append(
    chunkInserts(
      'performance_show_setlist_items',
      ['performance_id', 'show_key', 'position', 'source_position', 'song_id', 'medley_id', 'evidence', 'notes'],
      build.items.map((row) => [
        row.performance_id,
        row.show_key,
        row.position,
        row.source_position,
        row.song_id,
        row.medley_id,
        row.evidence,
        row.notes,
      ]),
    ),
  )
  append(
    chunkInserts(
      'medleys',
      ['id', 'name', 'note', 'source_url'],
      build.medleys.map((row) => [row.id, row.name, row.note, row.source_url]),
    ),
  )
  append(
    chunkInserts(
      'medley_songs',
      ['medley_id', 'position', 'song_id'],
      build.medleySongs.map((row) => [row.medley_id, row.position, row.song_id]),
    ),
  )
  parts.push('')
  return parts.join('\n')
}

/** Derives the tables from the committed SQL and the curation file. */
export const derivePerformanceSetlists = (
  root = repoRoot(),
): { sql: string; build: PerformanceSetlistBuild } => {
  const catalog = readCatalog(root)
  const review = reviewRotations(catalog)
  const curation: PerformanceSetlistCurationIndex = parsePerformanceSetlistCuration(readCuration(root))
  validateCurationAgainstCatalog(curation, catalog, review)
  const build = buildPerformanceSetlists(catalog, review, curation)
  return { sql: renderPerformanceSetlists(build, new Date().toISOString()), build }
}

/** Compares the generated increment with the committed one without writing. */
const checkExisting = (root: string, sql: string): number => {
  let existing = ''
  try {
    existing = readFileSync(path.join(root, TARGET), 'utf8')
  } catch {
    existing = ''
  }
  // The header carries a timestamp, so compare only the body.
  const body = (text: string): string => text.split('\n').filter((line) => !line.startsWith('-- Generated:')).join('\n')
  if (body(existing) === body(sql)) return 0
  console.error(`${TARGET} is out of date. Run pnpm derive:setlists.`)
  return 1
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename
if (isDirectRun) {
  const root = repoRoot()
  const { sql, build } = derivePerformanceSetlists(root)
  if (process.argv.includes('--check')) {
    const stale = checkExisting(root, sql)
    if (stale > 0) process.exit(stale)
    console.log('Performance setlist increment is up to date.')
    process.exit(0)
  }
  const target = path.join(root, TARGET)
  mkdirSync(path.dirname(target), { recursive: true })
  writeFileSync(target, sql)
  console.log(`Wrote ${target}`)
  console.log(
    `${build.stats.performances} performances, ${build.stats.shows} shows, ${build.stats.items} items, ` +
      `${build.stats.omittedRows} omitted rows, ${build.stats.pendingReview} pending review, ${build.stats.conflicts} conflicts`,
  )
}
