/** One 场次 of a 演出 in the timeline asset: its key, calendar position, and songs. */
export type TimelineAssetShow = {
  key: string
  date: string | null
  half: 'day' | 'night' | null
  /** Song ids in printed order; medley rows are already expanded into their parts. */
  songs: number[]
}

/** One 演出 reduced to the fields the timeline aggregation reads. */
export type TimelineAssetPerformance = {
  id: number
  seriesId: number
  name: string
  nameJa: string | null
  seriesSuffix: string | null
  venue: string | null
  countryCode: string | null
  startDate: string | null
  role: PerformanceRole
  shows: TimelineAssetShow[]
}

/** One song reduced to the credits the character and producer rules read, plus its display names. */
export type TimelineAssetSong = {
  id: number
  name: string
  nameJa: string | null
  nameZh: string | null
  artistString: string | null
  vocalists: string[]
  producers: SongProducerCredit[]
}

/** Compact catalog the Worker rebuilds before aggregating; generated by `build:catalog`. */
export type TimelineAsset = {
  generatedAt: string
  catalogVersion: string
  /** Series id and stored name, so the API can label a row without another request. */
  series: { id: number; name: string }[]
  songs: TimelineAssetSong[]
  performances: TimelineAssetPerformance[]
  /** Raw `data/characters.json`, parsed at runtime so both paths share one rule set. */
  characters: unknown
  /** Raw `data/song-variants.json`. */
  variants: unknown
  /** Raw `data/place-names.zh-CN.json` and `data/place-names.en.json`. */
  places: NameMapInput
}

/** Inputs the build needs besides the catalog itself. */
export type TimelineAssetInput = {
  catalog: Catalog
  generatedAt: string
  catalogVersion: string
  /** Chinese title of one song, or null when `data/song-titles.zh-CN.json` lists none. */
  nameZhOf: (songId: number) => string | null
  /** Raw `data/characters.json`. */
  characters: unknown
  /** Raw `data/song-variants.json`. */
  variants: unknown
  /** Raw `data/place-names.zh-CN.json` and `data/place-names.en.json`. */
  places: NameMapInput
}

/**
 * Effective 场次 keys of every 演出, with each key carrying the songs the timeline attributes to it.
 *
 * The schedule list comes from `showCountsByPerformance`'s two sources (derived layer first, note
 * fallback second), so a 演出 with no recorded song still contributes its 场次 count exactly like
 * the page. Songs come from `timelineSetlists`; a 场次 the schedule knows but no setlist spends
 * stays in the asset with an empty list instead of disappearing.
 */
const effectiveShows = (catalog: Catalog): Map<number, TimelineAssetShow[]> => {
  const setlists = timelineSetlists(catalog)
  const schedules = performanceSchedules(catalog, reviewRotations(catalog))
  for (const [id, shows] of catalogSchedules(catalog)) schedules.set(id, shows)
  const result = new Map<number, TimelineAssetShow[]>()
  for (const performance of catalog.performances) {
    const songsByShow = new Map((setlists.get(performance.id)?.byShow ?? []).map((unit) => [unit.key, unit.songIds]))
    const shows = [...(schedules.get(performance.id) ?? [])]
      .sort((left, right) => left.key.localeCompare(right.key))
      .map((show) => ({
        key: show.key,
        date: show.date === '' ? null : show.date,
        half: show.half,
        songs: songsByShow.get(show.key) ?? [],
      }))
    result.set(performance.id, shows)
  }
  return result
}

/**
 * Reduces a catalog to the timeline asset.
 *
 * The per-场次 song sets come from `timelineSetlists`, the same map `buildTimeline` reads, so a
 * rebuilt catalog yields the same numbers instead of a second derivation. Shows are sorted by key,
 * matching the `performance_show_setlists` query order the aggregation depends on.
 */
export const buildTimelineAsset = (input: TimelineAssetInput): TimelineAsset => {
  const { catalog } = input
  const shows = effectiveShows(catalog)
  return {
    generatedAt: input.generatedAt,
    catalogVersion: input.catalogVersion,
    series: catalog.series.map((series) => ({ id: series.id, name: series.name })),
    songs: catalog.songs.map((song): TimelineAssetSong => ({
      id: song.id,
      name: song.name,
      nameJa: song.name_ja,
      nameZh: input.nameZhOf(song.id),
      artistString: song.artist_string,
      vocalists: song.vocalists ?? [],
      producers: song.producers ?? [],
    })),
    performances: catalog.performances.map((performance): TimelineAssetPerformance => ({
      id: performance.id,
      seriesId: performance.series_id,
      name: performance.name,
      nameJa: performance.name_ja,
      seriesSuffix: performance.series_suffix,
      venue: performance.venue_name,
      countryCode: performance.country_code,
      startDate: performance.start_date,
      role: performance.role,
      shows: shows.get(performance.id) ?? [],
    })),
    characters: input.characters,
    variants: input.variants,
    places: input.places,
  }
}

/** 演出 row with the columns the aggregation reads; unused columns stay empty. */
const performanceRow = (row: TimelineAssetPerformance): PerformanceRow => ({
  id: row.id,
  series_id: row.seriesId,
  name: row.name,
  name_ja: row.nameJa,
  venue_name: row.venue,
  country_code: row.countryCode,
  start_date: row.startDate,
  end_date: null,
  showtime_local: null,
  timezone: null,
  time_precision: 'day',
  time_evidence: null,
  role: row.role,
  series_number: null,
  series_suffix: row.seriesSuffix,
  song_list_id: null,
  vocadb_status: null,
  source_url: '',
  retrieved_at: '',
})

/** Song row with the credits and names the aggregation reads. */
const songRow = (row: TimelineAssetSong): SongRow => ({
  id: row.id,
  name: row.name,
  name_ja: row.nameJa,
  name_en: null,
  artist_string: row.artistString,
  song_type: 'Original',
  category: 'vocaloid',
  publish_date: null,
  length_seconds: null,
  vocalists: row.vocalists,
  producers: row.producers,
  source_url: '',
  retrieved_at: '',
})

/**
 * Rebuilds a catalog from the asset.
 *
 * Every 演出 carries its own derived 场次 rows, which `showCountsByPerformance` and
 * `buildSongsByPerformance` read first, so an equivalent catalog needs no source setlist layer.
 */
export const timelineCatalogFromAsset = (asset: TimelineAsset): Catalog => {
  const performanceShowSetlists: PerformanceShowSetlistRow[] = []
  const performanceShowSetlistItems: PerformanceShowSetlistItemRow[] = []
  for (const performance of asset.performances) {
    for (const show of performance.shows) {
      performanceShowSetlists.push({
        performance_id: performance.id,
        show_key: show.key,
        date: show.date,
        half: show.half,
        item_count: show.songs.length,
        omitted_count: 0,
        uncertain: 0,
        reasons: '[]',
      })
      show.songs.forEach((songId, index) => {
        performanceShowSetlistItems.push({
          performance_id: performance.id,
          show_key: show.key,
          position: index + 1,
          source_position: null,
          song_id: songId,
          medley_id: null,
          evidence: 'note',
          notes: null,
        })
      })
    }
  }
  return {
    sources: [],
    series: asset.series.map((series) => ({
      id: series.id,
      name: series.name,
      name_ja: null,
      description: null,
      source_url: '',
      retrieved_at: '',
    })),
    performances: asset.performances.map(performanceRow),
    performanceLinks: [],
    premieres: [],
    songLists: [],
    songs: asset.songs.map(songRow),
    setlistItems: [],
    setlistItemSongs: [],
    medleyQuarantine: [],
    videos: [],
    performanceSetlists: [],
    performanceSetlistSources: [],
    performanceShowSetlists,
    performanceShowSetlistItems,
    medleys: [],
    medleySongs: [],
    performanceStatus: [],
  }
}

/** Character rules shipped in the asset, parsed with the same config parser the pages use. */
export const timelineCharactersFromAsset = (asset: TimelineAsset): CharacterRule[] =>
  parseCharacterConfig(asset.characters)

/** Variant index shipped in the asset, for the optional version merge. */
export const timelineVariantsFromAsset = (asset: TimelineAsset): SongVariantIndex =>
  parseSongVariants(asset.variants)

/** Checked place list shipped in the asset, for the city filter and the city charts. */
export const timelineCityIndexFromAsset = (asset: TimelineAsset): CityIndex =>
  buildCityIndex(parsePlaceNames(asset.places))

/** Display names of every song in the asset, keyed by id. */
export const timelineSongNamesFromAsset = (
  asset: TimelineAsset,
): Map<number, { name: string; nameJa: string | null; nameZh: string | null }> =>
  new Map(asset.songs.map((song) => [song.id, { name: song.name, nameJa: song.nameJa, nameZh: song.nameZh }]))
